def _render_api_client() -> str:
    return _header() + dedent("""\
        interface Envelope<T> { code: string; message: string; data: T }

        export class ApiError extends Error {
          constructor(public code: string, message: string, public status: number) {
            super(message)
          }
        }

        async function request<T>(path: string, init?: RequestInit): Promise<T> {
          const response = await fetch(path, {
            ...init,
            headers: { 'Content-Type': 'application/json', ...(init?.headers ?? {}) },
          })
          const body = await response.json() as Envelope<T>
          if (!response.ok || body.code !== 'OK') {
            throw new ApiError(body.code || 'REQUEST_FAILED', body.message || '请求失败', response.status)
          }
          return body.data
        }

        export const crudApi = {
          list: (route: string) => request<Record<string, unknown>[]>(`/api/v1${route}`),
          detail: (route: string, id: unknown) => request<Record<string, unknown>>(`/api/v1${route}/${id}`),
          create: (route: string, input: Record<string, unknown>) => request<Record<string, unknown>>(`/api/v1${route}`, { method: 'POST', body: JSON.stringify(input) }),
          update: (route: string, id: unknown, input: Record<string, unknown>) => request<Record<string, unknown>>(`/api/v1${route}/${id}`, { method: 'PUT', body: JSON.stringify(input) }),
          remove: (route: string, id: unknown) => request<void>(`/api/v1${route}/${id}`, { method: 'DELETE' }),
        }
        """)


def _render_module_contract(contract: dict[str, Any]) -> str:
    modules = []
    for module in contract["modules"]:
        modules.append({
            "id": module["id"],
            "name": module["name"],
            "route": module["route"],
            "actions": module["actions"],
            "fields": [
                {
                    "code": field["code"],
                    "label": field["label"],
                    "type": field["type"],
                    "required": field["required"],
                    "list": field["list"],
                    "form": field["form"],
                    "filter": field["filter"],
                }
                for field in module["fields"]
            ],
        })
    literal = json.dumps(modules, ensure_ascii=False, indent=2)
    return _header() + dedent(f"""\
        export type GeneratedFieldType = 'id' | 'string' | 'text' | 'integer' | 'decimal' | 'boolean' | 'date' | 'datetime'
        export interface GeneratedField {{
          readonly code: string
          readonly label: string
          readonly type: GeneratedFieldType
          readonly required: boolean
          readonly list: boolean
          readonly form: boolean
          readonly filter: boolean
        }}
        export interface GeneratedModule {{
          readonly id: string
          readonly name: string
          readonly route: string
          readonly actions: readonly string[]
          readonly fields: readonly GeneratedField[]
        }}

        export const modules = {literal} as const satisfies readonly GeneratedModule[]
        """)


def _render_crud_view() -> str:
    return _header("<!--").rstrip("\n") + " -->\n" + dedent("""\
        <script setup lang="ts">
        import { computed, onMounted, reactive, ref, watch } from 'vue'
        import { useRoute } from 'vue-router'
        import { message } from 'ant-design-vue'
        import { crudApi } from '../api/client'
        import { modules, type GeneratedField } from '../generated/modules'

        const route = useRoute()
        const module = computed(() => modules.find(item => item.id === route.meta.moduleId) ?? modules[0])
        const rows = ref<Record<string, unknown>[]>([])
        const loading = ref(false)
        const error = ref('')
        const search = ref('')
        const detailOpen = ref(false)
        const detail = ref<Record<string, unknown>>({})
        const formOpen = ref(false)
        const editingId = ref<unknown>(null)
        const saving = ref(false)
        const form = reactive<Record<string, unknown>>({})

        const listFields = computed(() => module.value.fields.filter(field => field.list))
        const formFields = computed(() => module.value.fields.filter(field => field.form))
        const searchFields = computed(() => module.value.fields.filter(field => field.filter && ['string', 'text'].includes(field.type)))
        const columns = computed(() => [
          ...listFields.value.map(field => ({ title: field.label, dataIndex: field.code, key: field.code })),
          { title: '操作', key: '_actions', width: 120 },
        ])
        const visibleRows = computed(() => {
          const keyword = search.value.trim().toLowerCase()
          if (!keyword) return rows.value
          return rows.value.filter(row => searchFields.value.some(field => String(row[field.code] ?? '').toLowerCase().includes(keyword)))
        })

        function emptyValue(field: GeneratedField): unknown {
          if (field.type === 'boolean') return false
          if (field.type === 'integer' || field.type === 'decimal') return null
          return ''
        }
        function resetForm(row?: Record<string, unknown>) {
          for (const field of formFields.value) form[field.code] = row?.[field.code] ?? emptyValue(field)
        }
        async function load() {
          loading.value = true
          error.value = ''
          try { rows.value = await crudApi.list(module.value.route) }
          catch (cause) { error.value = cause instanceof Error ? cause.message : '数据加载失败' }
          finally { loading.value = false }
        }
        function openCreate() {
          editingId.value = null
          resetForm()
          formOpen.value = true
        }
        function openEdit(row: Record<string, unknown>) {
          editingId.value = row.id
          resetForm(row)
          formOpen.value = true
        }
        async function save() {
          saving.value = true
          try {
            if (editingId.value == null) await crudApi.create(module.value.route, { ...form })
            else await crudApi.update(module.value.route, editingId.value, { ...form })
            formOpen.value = false
            message.success(editingId.value == null ? '创建成功' : '保存成功')
            await load()
          } catch (cause) {
            message.error(cause instanceof Error ? cause.message : '保存失败')
          } finally { saving.value = false }
        }
        async function openDetail(row: Record<string, unknown>) {
          detail.value = await crudApi.detail(module.value.route, row.id)
          detailOpen.value = true
        }
        async function remove(row: Record<string, unknown>) {
          if (!window.confirm(`确认删除这条${module.value.name}？`)) return
          await crudApi.remove(module.value.route, row.id)
          message.success('删除成功')
          await load()
        }
        function display(field: GeneratedField, value: unknown) {
          if (field.type === 'boolean') return value ? '是' : '否'
          return value == null || value === '' ? '—' : String(value)
        }
        function isNumberField(type: GeneratedField['type']) {
          return ['integer', 'decimal'].includes(type)
        }

        watch(() => route.meta.moduleId, () => void load())
        onMounted(load)
        </script>

        <template>
          <main class="module-page">
            <header class="page-header">
              <div><h1>{{ module.name }}</h1><p>查看和维护{{ module.name }}数据</p></div>
              <a-button v-if="module.actions.includes('create')" type="primary" @click="openCreate">新建{{ module.name }}</a-button>
            </header>

            <a-alert v-if="error" class="error-panel" type="error" show-icon :message="error">
              <template #action><a-button size="small" @click="load">重新加载</a-button></template>
            </a-alert>

            <section class="table-card">
              <div class="table-toolbar">
                <a-input-search v-model:value="search" class="search" allow-clear placeholder="输入关键词快速搜索" />
                <span>{{ visibleRows.length }} 条记录</span>
              </div>
              <a-table
                :columns="columns"
                :data-source="visibleRows"
                :loading="loading"
                row-key="id"
                :pagination="{ pageSize: 20, showSizeChanger: false }"
                :custom-row="(row: Record<string, unknown>) => ({ class: 'clickable-row', onClick: () => openDetail(row) })"
              >
                <template #bodyCell="{ column, record }">
                  <template v-if="column.key === '_actions'">
                    <span class="row-actions" @click.stop>
                      <a-button v-if="module.actions.includes('update')" type="link" @click="openEdit(record)">编辑</a-button>
                      <a-button v-if="module.actions.includes('delete')" type="link" danger @click="remove(record)">删除</a-button>
                    </span>
                  </template>
                  <template v-else>{{ display(module.fields.find(field => field.code === column.key)!, record[column.key]) }}</template>
                </template>
                <template #emptyText><div class="state-panel">暂无数据，可以从“新建{{ module.name }}”开始。</div></template>
              </a-table>
            </section>

            <a-drawer v-model:open="detailOpen" :title="`${module.name}详情`" width="520">
              <dl class="detail-list">
                <div v-for="field in module.fields" :key="field.code">
                  <dt>{{ field.label }}</dt><dd>{{ display(field, detail[field.code]) }}</dd>
                </div>
              </dl>
            </a-drawer>

            <a-modal v-model:open="formOpen" :title="editingId == null ? `新建${module.name}` : `编辑${module.name}`" ok-text="保存" cancel-text="取消" :confirm-loading="saving" @ok="save">
              <a-form layout="vertical">
                <a-form-item v-for="field in formFields" :key="field.code" :label="field.label" :required="field.required">
                  <a-switch v-if="field.type === 'boolean'" v-model:checked="form[field.code]" :data-testid="`field-${field.code}`" />
                  <a-input-number v-else-if="isNumberField(field.type)" v-model:value="form[field.code]" style="width: 100%" :data-testid="`field-${field.code}`" />
                  <a-textarea v-else-if="field.type === 'text'" v-model:value="form[field.code]" :rows="4" :data-testid="`field-${field.code}`" />
                  <a-input v-else v-model:value="form[field.code]" :data-testid="`field-${field.code}`" />
                </a-form-item>
              </a-form>
            </a-modal>
          </main>
        </template>
        """)


def _example_value(field: dict[str, Any]) -> Any:
    kind = field["type"]
    if kind == "string":
        return "TB-REAL-001" if field.get("unique") else f"真实{field['label']}"
    if kind == "text":
        return "由真实浏览器写入真实后端和 MySQL"
    if kind == "integer":
        return 2
    if kind == "decimal":
        return 12.5
    if kind == "boolean":
        return True
    if kind == "date":
        return "2026-08-11"
    if kind == "datetime":
        return "2026-08-11T12:00:00"
    return None


def _render_real_e2e(contract: dict[str, Any]) -> str:
    module = contract["modules"][0]
    form_fields = [field for field in module["fields"] if field["form"]]
    actions: list[str] = []
    expected_text = ""
    for field in form_fields:
        value = _example_value(field)
        if field["type"] == "boolean":
            if value:
                actions.append(f"  await page.getByTestId('field-{field['code']}').click()")
        elif field["type"] in {"integer", "decimal"}:
            actions.append(f"  await page.getByTestId('field-{field['code']}').fill('{value}')")
        else:
            actions.append(f"  await page.getByTestId('field-{field['code']}').fill({json.dumps(str(value), ensure_ascii=False)})")
        if not expected_text and field["list"] and field["type"] in {"string", "text"}:
            expected_text = str(value)
    if not expected_text:
        expected_text = str(_example_value(form_fields[0]))
    return _header() + dedent(f"""\
        import {{ expect, test }} from '@playwright/test'

        test('real browser writes through the real API and reads the persisted row back', async ({{ page }}) => {{
          const unexpectedResponses: string[] = []
          page.on('response', response => {{
            if (response.url().includes('/api/') && response.status() >= 400) unexpectedResponses.push(`${{response.status()}} ${{response.url()}}`)
          }})

          await page.goto({json.dumps(module['route'], ensure_ascii=False)})
          await expect(page.getByRole('heading', {{ name: {json.dumps(module['name'], ensure_ascii=False)} }})).toBeVisible()
          await page.getByRole('button', {{ name: {json.dumps('新建' + module['name'], ensure_ascii=False)} }}).click()
        {chr(10).join(actions)}
          await page.getByRole('dialog').getByRole('button', {{ name: /保\\s*存/ }}).click()

          await expect(page.getByText({json.dumps(expected_text, ensure_ascii=False)}, {{ exact: true }})).toBeVisible()
          await page.reload()
          await expect(page.getByText({json.dumps(expected_text, ensure_ascii=False)}, {{ exact: true }})).toBeVisible()
          await page.getByText({json.dumps(expected_text, ensure_ascii=False)}, {{ exact: true }}).click()
          await expect(page.getByText({json.dumps(module['name'] + '详情', ensure_ascii=False)}, {{ exact: true }})).toBeVisible()
          expect(unexpectedResponses).toEqual([])
        }})
        """)


