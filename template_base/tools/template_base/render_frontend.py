def _header(comment: str = "//") -> str:
    return f"{comment} @generated by Template Base. Do not edit by hand.\n"


def render_frontend(contract: dict[str, Any]) -> dict[str, str]:
    project = contract["project"]
    runtime = contract["runtime"]
    files: dict[str, str] = {
        "frontend/package.json": _render_package_json(project),
        "frontend/tsconfig.json": _render_tsconfig(),
        "frontend/vite.config.ts": _render_vite_config(runtime),
        "frontend/playwright.config.ts": _render_playwright_config(),
        "frontend/index.html": _render_index(project),
        "frontend/src/main.ts": _render_main(),
        "frontend/src/App.vue": _render_app(contract),
        "frontend/src/styles.css": _render_styles(),
        "frontend/src/router.ts": _render_router(contract),
        "frontend/src/api/client.ts": _render_api_client(),
        "frontend/src/generated/modules.ts": _render_module_contract(contract),
        "frontend/src/views/GeneratedCrudView.vue": _render_crud_view(),
        "frontend/tests/e2e/real-crud.spec.ts": _render_real_e2e(contract),
    }
    return files


