JAVA_TYPES = {
    "id": "Long",
    "string": "String",
    "text": "String",
    "integer": "Integer",
    "decimal": "BigDecimal",
    "boolean": "Boolean",
    "date": "LocalDate",
    "datetime": "LocalDateTime",
}


def _header(comment: str = "//") -> str:
    return f"{comment} @generated by Template Base. Do not edit by hand.\n"


def _imports_for(fields: list[dict[str, Any]]) -> list[str]:
    types = {field["type"] for field in fields}
    imports: list[str] = []
    if "decimal" in types:
        imports.append("java.math.BigDecimal")
    if "date" in types:
        imports.append("java.time.LocalDate")
    if "datetime" in types:
        imports.append("java.time.LocalDateTime")
    return imports


def _sql_type(field: dict[str, Any]) -> str:
    kind = field["type"]
    if kind == "id":
        return "BIGINT"
    if kind == "string":
        return f"VARCHAR({field['length']})"
    if kind == "text":
        return "TEXT"
    if kind == "integer":
        return "INT"
    if kind == "decimal":
        return "DECIMAL(19,4)"
    if kind == "boolean":
        return "TINYINT(1)"
    if kind == "date":
        return "DATE"
    if kind == "datetime":
        return "DATETIME(3)"
    raise ValueError(f"unsupported field type: {kind}")


def _validation_annotations(field: dict[str, Any]) -> list[str]:
    annotations: list[str] = []
    if field.get("required"):
        if field["type"] in {"string", "text"}:
            annotations.append('@NotBlank(message = "不能为空")')
        else:
            annotations.append('@NotNull(message = "不能为空")')
    if field["type"] == "string":
        annotations.append(f'@Size(max = {field["length"]}, message = "长度不能超过 {field["length"]}")')
    return annotations


