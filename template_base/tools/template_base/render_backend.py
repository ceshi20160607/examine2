def _render_migration(contract: dict[str, Any]) -> str:
    chunks = [_header("--").rstrip(), "SET NAMES utf8mb4;"]
    for module in contract["modules"]:
        columns: list[str] = []
        unique_columns: list[str] = []
        for field in module["fields"]:
            line = f"  `{field['column']}` {_sql_type(field)}"
            if field["type"] == "id":
                line += " NOT NULL AUTO_INCREMENT"
            elif field.get("required"):
                line += " NOT NULL"
            else:
                line += " NULL"
            if field["type"] == "datetime" and field["code"] == "createdAt":
                line += " DEFAULT CURRENT_TIMESTAMP(3)"
            columns.append(line)
            if field.get("unique"):
                unique_columns.append(field["column"])
        columns.append("  PRIMARY KEY (`id`)")
        for column in unique_columns:
            columns.append(f"  UNIQUE KEY `uk_{module['table']}_{column}` (`{column}`)")
        body = ",\n".join(columns)
        chunks.append(f"CREATE TABLE `{module['table']}` (\n{body}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;")
    return "\n\n".join(chunks) + "\n"


def _render_entity(package: str, module: dict[str, Any]) -> str:
    class_name = pascal(module["id"])
    imports = [
        "com.baomidou.mybatisplus.annotation.IdType",
        "com.baomidou.mybatisplus.annotation.TableField",
        "com.baomidou.mybatisplus.annotation.TableId",
        "com.baomidou.mybatisplus.annotation.TableName",
        *_imports_for(module["fields"]),
    ]
    import_text = "\n".join(f"import {item};" for item in sorted(imports))
    fields: list[str] = []
    accessors: list[str] = []
    for field in module["fields"]:
        java_type = JAVA_TYPES[field["type"]]
        if field["type"] == "id":
            annotation = '    @TableId(value = "id", type = IdType.AUTO)'
        else:
            annotation = f'    @TableField("{field["column"]}")'
        fields.append(f"{annotation}\n    private {java_type} {field['code']};")
        method = field["code"][:1].upper() + field["code"][1:]
        accessors.append(dedent(f"""\
                public {java_type} get{method}() {{
                    return {field['code']};
                }}

                public void set{method}({java_type} {field['code']}) {{
                    this.{field['code']} = {field['code']};
                }}
            """).rstrip())
    return _header() + dedent(f"""\
        package {package}.base.entity;

        {import_text}

        @TableName("{module['table']}")
        public class {class_name} {{
        {chr(10).join(fields)}

        {chr(10).join(accessors)}
        }}
        """)


