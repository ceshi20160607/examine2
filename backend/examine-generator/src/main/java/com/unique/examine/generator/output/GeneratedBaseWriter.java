package com.unique.examine.generator.output;

import com.unique.examine.generator.GeneratorModule;
import com.unique.examine.generator.GeneratorModuleRegistry;
import com.unique.examine.generator.sql.SqlColumn;
import com.unique.examine.generator.sql.SqlTable;
import java.io.IOException;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.util.Collection;
import java.util.Comparator;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;
import java.util.TreeMap;
import java.util.stream.Collectors;

/**
 * Writes deterministic base entity, mapper, service, service implementation, and XML files.
 */
public final class GeneratedBaseWriter {

    private static final String GENERATED_HEADER = """
            // <auto-generated>
            // Generated from sql/init.sql by examine-generator. Do not hand edit.
            // </auto-generated>
            """;

    private final Path backendRoot;

    public GeneratedBaseWriter(Path backendRoot) {
        this.backendRoot = backendRoot;
    }

    /**
     * Generate base files for every table with a registered module prefix.
     *
     * @param tables parsed SQL table metadata
     * @return summary of generated and unresolved tables
     * @throws IOException when files cannot be written
     */
    public GenerationSummary write(List<SqlTable> tables) throws IOException {
        GenerationSummary summary = new GenerationSummary();
        for (SqlTable table : tables) {
            Optional<GeneratorModule> module = GeneratorModuleRegistry.resolve(table.name());
            if (module.isEmpty()) {
                summary.unresolvedTables.add(table.name());
                continue;
            }
            writeTable(module.get(), table);
            summary.generatedByModule.merge(module.get().moduleName(), 1, Integer::sum);
        }
        return summary;
    }

    private void writeTable(GeneratorModule module, SqlTable table) throws IOException {
        String entityName = toClassName(stripUnPrefix(table.name()));
        String mapperName = entityName + "Mapper";
        String serviceName = entityName + "BaseService";
        String serviceImplName = entityName + "BaseServiceImpl";
        String basePackage = module.basePackage();
        Path javaRoot = backendRoot.resolve(module.javaSourceRoot());
        Path xmlRoot = backendRoot.resolve(module.mapperXmlRoot());

        write(javaRoot.resolve(packagePath(basePackage + ".entity")).resolve(entityName + ".java"),
                renderEntity(basePackage, entityName, table));
        write(javaRoot.resolve(packagePath(basePackage + ".mapper")).resolve(mapperName + ".java"),
                renderMapper(basePackage, entityName, mapperName, table));
        write(javaRoot.resolve(packagePath(basePackage + ".service")).resolve(serviceName + ".java"),
                renderService(basePackage, entityName, serviceName));
        write(javaRoot.resolve(packagePath(basePackage + ".service.impl")).resolve(serviceImplName + ".java"),
                renderServiceImpl(basePackage, entityName, serviceName, serviceImplName));
        write(xmlRoot.resolve(mapperName + ".xml"),
                renderMapperXml(basePackage, entityName, mapperName, table));
    }

    private String renderEntity(String basePackage, String entityName, SqlTable table) {
        Set<String> imports = table.columns().stream()
                .map(this::javaType)
                .map(this::importForType)
                .filter(Optional::isPresent)
                .map(Optional::get)
                .collect(Collectors.toCollection(LinkedHashSet::new));
        imports.add("com.baomidou.mybatisplus.annotation.IdType");
        imports.add("com.baomidou.mybatisplus.annotation.TableId");
        imports.add("com.baomidou.mybatisplus.annotation.TableName");

        StringBuilder builder = new StringBuilder();
        builder.append(GENERATED_HEADER)
                .append("package ").append(basePackage).append(".entity;\n\n");
        for (String importLine : imports) {
            builder.append("import ").append(importLine).append(";\n");
        }
        if (!imports.isEmpty()) {
            builder.append('\n');
        }
        builder.append("/**\n")
                .append(" * Generated entity for table `").append(table.name()).append("`.\n")
                .append(" */\n")
                .append("@TableName(\"").append(table.name()).append("\")\n")
                .append("public class ").append(entityName).append(" {\n\n")
                .append("    public static final String TABLE_NAME = \"").append(table.name()).append("\";\n\n");
        for (SqlColumn column : table.columns()) {
            builder.append("    /**\n")
                    .append("     * Column `").append(column.name()).append("`.\n")
                    .append("     */\n")
                    .append(column.primaryKey() ? "    @TableId(value = \"" + column.name() + "\", type = IdType.AUTO)\n" : "")
                    .append("    private ").append(javaType(column)).append(' ').append(toFieldName(column.name())).append(";\n\n");
        }
        for (SqlColumn column : table.columns()) {
            String type = javaType(column);
            String field = toFieldName(column.name());
            String methodSuffix = capitalize(field);
            builder.append("    public ").append(type).append(" get").append(methodSuffix).append("() {\n")
                    .append("        return ").append(field).append(";\n")
                    .append("    }\n\n")
                    .append("    public void set").append(methodSuffix).append('(').append(type).append(' ').append(field).append(") {\n")
                    .append("        this.").append(field).append(" = ").append(field).append(";\n")
                    .append("    }\n\n");
        }
        builder.append("}\n");
        return builder.toString();
    }

    private String renderMapper(String basePackage, String entityName, String mapperName, SqlTable table) {
        return GENERATED_HEADER
                + "package " + basePackage + ".mapper;\n\n"
                + "import com.baomidou.mybatisplus.core.mapper.BaseMapper;\n"
                + "import " + basePackage + ".entity." + entityName + ";\n\n"
                + "import org.apache.ibatis.annotations.Mapper;\n\n"
                + "/**\n"
                + " * Generated mapper contract for table `" + table.name() + "`.\n"
                + " */\n"
                + "@Mapper\n"
                + "public interface " + mapperName + " extends BaseMapper<" + entityName + "> {\n\n"
                + "    String TABLE_NAME = " + entityName + ".TABLE_NAME;\n"
                + "}\n";
    }

    private String renderService(String basePackage, String entityName, String serviceName) {
        return GENERATED_HEADER
                + "package " + basePackage + ".service;\n\n"
                + "import com.baomidou.mybatisplus.extension.service.IService;\n"
                + "import " + basePackage + ".entity." + entityName + ";\n"
                + "import java.util.Collection;\n"
                + "import java.util.List;\n"
                + "import java.util.Optional;\n\n"
                + "/**\n"
                + " * Generated base service contract for " + entityName + ".\n"
                + " */\n"
                + "public interface " + serviceName + " extends IService<" + entityName + "> {\n\n"
                + "    Optional<" + entityName + "> findById(Long id);\n\n"
                + "    List<" + entityName + "> findAll();\n\n"
                + "    " + entityName + " saveEntity(" + entityName + " entity);\n\n"
                + "    boolean deleteByIds(Collection<Long> ids);\n"
                + "}\n";
    }

    private String renderServiceImpl(String basePackage, String entityName, String serviceName, String serviceImplName) {
        return GENERATED_HEADER
                + "package " + basePackage + ".service.impl;\n\n"
                + "import com.baomidou.mybatisplus.extension.service.impl.ServiceImpl;\n"
                + "import " + basePackage + ".entity." + entityName + ";\n"
                + "import " + basePackage + ".mapper." + entityName + "Mapper;\n"
                + "import " + basePackage + ".service." + serviceName + ";\n"
                + "import java.util.Collection;\n"
                + "import java.util.List;\n"
                + "import java.util.Optional;\n\n"
                + "import org.springframework.stereotype.Service;\n\n"
                + "/**\n"
                + " * Generated MyBatis-Plus base service implementation for " + entityName + ".\n"
                + " */\n"
                + "@Service\n"
                + "public class " + serviceImplName + " extends ServiceImpl<" + entityName + "Mapper, " + entityName + "> implements " + serviceName + " {\n\n"
                + "    @Override\n"
                + "    public Optional<" + entityName + "> findById(Long id) {\n"
                + "        return Optional.ofNullable(getById(id));\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    public List<" + entityName + "> findAll() {\n"
                + "        return list();\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    public " + entityName + " saveEntity(" + entityName + " entity) {\n"
                + "        saveOrUpdate(entity);\n"
                + "        return entity;\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    public boolean deleteByIds(Collection<Long> ids) {\n"
                + "        return ids != null && !ids.isEmpty() && removeBatchByIds(ids);\n"
                + "    }\n"
                + "}\n";
    }

    private String renderMapperXml(String basePackage, String entityName, String mapperName, SqlTable table) {
        String namespace = basePackage + ".mapper." + mapperName;
        String type = basePackage + ".entity." + entityName;
        String resultMap = table.columns().stream()
                .map(column -> "        <" + (column.primaryKey() ? "id" : "result") + " column=\""
                        + column.name() + "\" property=\"" + toFieldName(column.name()) + "\" />")
                .collect(Collectors.joining("\n"));
        String columnList = table.columns().stream()
                .map(SqlColumn::name)
                .collect(Collectors.joining(", "));
        return """
                <?xml version="1.0" encoding="UTF-8"?>
                <!DOCTYPE mapper PUBLIC "-//mybatis.org//DTD Mapper 3.0//EN" "https://mybatis.org/dtd/mybatis-3-mapper.dtd">
                <!--
                  Generated from sql/init.sql by examine-generator. Do not hand edit.
                -->
                <mapper namespace="%s">
                    <resultMap id="BaseResultMap" type="%s">
                %s
                    </resultMap>

                    <sql id="BaseColumnList">%s</sql>
                </mapper>
                """.formatted(namespace, type, resultMap, columnList);
    }

    private void write(Path path, String content) throws IOException {
        Files.createDirectories(path.getParent());
        Files.writeString(path, content, StandardCharsets.UTF_8);
    }

    private String javaType(SqlColumn column) {
        return switch (column.sqlType().toUpperCase(Locale.ROOT)) {
            case "BIGINT" -> "Long";
            case "INT", "INTEGER", "TINYINT", "SMALLINT" -> "Integer";
            case "DECIMAL", "NUMERIC" -> BigDecimal.class.getSimpleName();
            case "DOUBLE", "FLOAT" -> "Double";
            case "DATE" -> LocalDate.class.getSimpleName();
            case "TIME" -> LocalTime.class.getSimpleName();
            case "DATETIME", "TIMESTAMP" -> LocalDateTime.class.getSimpleName();
            default -> "String";
        };
    }

    private Optional<String> importForType(String javaType) {
        return switch (javaType) {
            case "BigDecimal" -> Optional.of(BigDecimal.class.getName());
            case "LocalDate" -> Optional.of(LocalDate.class.getName());
            case "LocalTime" -> Optional.of(LocalTime.class.getName());
            case "LocalDateTime" -> Optional.of(LocalDateTime.class.getName());
            default -> Optional.empty();
        };
    }

    private String stripUnPrefix(String tableName) {
        return tableName.startsWith("un_") ? tableName.substring(3) : tableName;
    }

    private String toClassName(String value) {
        return snakeParts(value).stream()
                .map(this::capitalize)
                .collect(Collectors.joining());
    }

    private String toFieldName(String value) {
        String className = toClassName(value);
        return Character.toLowerCase(className.charAt(0)) + className.substring(1);
    }

    private String capitalize(String value) {
        if (value.isBlank()) {
            return value;
        }
        return Character.toUpperCase(value.charAt(0)) + value.substring(1);
    }

    private List<String> snakeParts(String value) {
        return List.of(value.split("_")).stream()
                .filter(part -> !part.isBlank())
                .map(part -> part.toLowerCase(Locale.ROOT))
                .toList();
    }

    private Path packagePath(String packageName) {
        return Path.of(packageName.replace('.', '/'));
    }

    /**
     * Generation run summary.
     */
    public static final class GenerationSummary {

        private final TreeMap<String, Integer> generatedByModule = new TreeMap<>(Comparator.naturalOrder());
        private final Set<String> unresolvedTables = new LinkedHashSet<>();

        public TreeMap<String, Integer> generatedByModule() {
            return new TreeMap<>(generatedByModule);
        }

        public Set<String> unresolvedTables() {
            return Set.copyOf(unresolvedTables);
        }
    }
}
